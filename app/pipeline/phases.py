from __future__ import annotations

import re

from ..textutil import norm

RULES = [
    (r"отцвет|конец цветения|окончание цветения|полное отцветание", "конец цветения"),
    (r"массов\w* цветени|разгар цветени|пик цветени", "массовое цветение"),
    (r"начал\w* цветени|зацвет|первые цветы|первые единичные цветы|раскрыти\w* цветк|пыление|появление сереж", "начало цветения"),
    (r"цвете", "цветение"),
    (r"зелен|распускани|развертыван|разворачиван|облиствен|«барашки»|барашки", "начало зеленения / распускания"),
    (r"листопад|пожелтени|осенн\w* окраск|покраснени", "осеннее окрашивание / листопад"),
    (r"поспеван|созреван|спел\w* ягод|плодоносени|плодоношени|созрели", "созревание плодов"),
    (r"рассеивани\w* семян|осыпани\w* семян|раскрыти\w* шишек", "рассеивание семян"),
    (r"прилет|прилёт|появлени\w* птиц|первая песня|первое кукование|песня", "прилёт / первая песня"),
    (r"отлет|отлёт|пролет|пролёт", "отлёт / пролёт"),
    (r"ледостав|замерзани|забереги", "ледостав"),
    (r"вскрыти|очищени\w* .* ото льда|ледоход", "вскрытие ото льда"),
    (r"снежн\w* покров|сход снега|первый снег|снегопад|снега покрыто", "снежный покров"),
    (r"появлени\w* (комар|мошк|шмел|слепн|стрекоз|бабоч|пчел)|вылет", "появление насекомых"),
    (r"нерест|кладк|выводок|икр", "размножение"),
]
_C = [(re.compile(p), name) for p, name in RULES]


def canon_phases(event: str, fragment: str = "") -> list[str]:
    s = norm(event)
    out = []
    for rx, name in _C:
        if rx.search(s) and name not in out:
            out.append(name)
            if name != "цветение":
                break
    if not out and fragment:
        s2 = norm(fragment)[:200]
        for rx, name in _C:
            if rx.search(s2):
                out.append(name)
                break
    return out
