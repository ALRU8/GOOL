from __future__ import annotations

import re

_SUBS = [
    (r"\bкв\.?\s*км\b|\bкм\s*2\b|\bкм²", "км²"),
    (r"\bкв\.?\s*м\b|\bм\s*2\b|\bм²", "м²"),
    (r"\bкв\.?\s*см\b|\bсм\s*2\b|\bсм²", "см²"),
    (r"\bэкземпляр\w*\b|\bэкз\.?|\bособ[ьи]\b|\bос\.", "особей"),
    (r"\bштук\w*\b|\bшт\.?", "шт"),
    (r"\bгнезд\w*\b", "гнёзд"),
    (r"\bсуток\b|\bсутки\b|\bдн\.?\b|\bдня\b", "дней"),
    (r"\bчасов\b|\bчаса\b|\bч\.?(?=\s|$)", "ч"),
    (r"\bпроцент\w*\b", "%"),
    (r"\bградус\w*\b", "°"),
    (r"°\s*[сc]\b", "°C"),
    (r"\bгектар\w*\b", "га"),
    (r"\bкилограмм\w*\b", "кг"),
    (r"\bграмм\w*\b", "г"),
    (r"\bмиллиметр\w*\b", "мм"),
    (r"\bсантиметр\w*\b", "см"),
    (r"\bкилометр\w*\b", "км"),
    (r"\bметр\w*\b", "м"),
]
_C = [(re.compile(p, re.I), r) for p, r in _SUBS]


def normalize_unit(u: str) -> str:
    s = (u or "").strip()
    if not s:
        return ""
    s = re.sub(r"\s+", " ", s)
    for rx, rep in _C:
        s = rx.sub(rep, s)
    s = re.sub(r"(?<=[а-яa-z])2(?!\d)", "²", s) if re.search(r"/\s*[а-яa-z]+2\b", s) else s
    s = re.sub(r"\s+на\s+(?=\d)", "/", s)
    s = re.sub(r"/\s*1\s+(?=[а-яa-z])", "/", s)
    s = s.strip(" .,;")
    return s.lower() if not re.search(r"[°²]", s) else s


TOPICS = [
    (r"календар|фенолог|сезонн\w* динамик\w* растит|сезонн\w* явлен", "Календарь природы и фенология"),
    (r"погод|климат|метео|осадк|температур|гидро", "Погода и климат"),
    (r"млекопитающ|мелк\w* млекопит", "Млекопитающие"),
    (r"птиц|орнитол", "Птицы"),
    (r"рыб|ихтио", "Рыбы"),
    (r"амфиби|рептил", "Амфибии и рептилии"),
    (r"беспозвоночн|насеком|энтомо|жемчужниц", "Беспозвоночные"),
    (r"гриб|лишайник|\bмх", "Грибы, лишайники, мхи"),
    (r"флор|растительн|геоботан|плодонош|ягодник|семеношен", "Флора и растительность"),
    (r"фаун|животн", "Фауна"),
    (r"территор|площад|ландшафт|почв|лес[аоу]|лесн|участк", "Территория, почвы, леса"),
    (r"охран|заповедн\w* режим|антропоген|рекреац|эколого", "Охрана и режим"),
    (r"научн\w* исслед|международн", "Научные исследования"),
]
_TC = [(re.compile(p, re.I), name) for p, name in TOPICS]


def topic_of(section: str) -> str:
    s = (section or "").strip()
    if not s:
        return ""
    for rx, name in _TC:
        if rx.search(s):
            return name
    return "Другое"


ALL_TOPICS = {name for _, name in TOPICS} | {"Другое", "—"}
